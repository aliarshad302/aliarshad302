export function getRawCities(): RawCityEntry[] {
  return raw.map(([name, population, county, slugOverride]) => ({
    name,
    population,
    county,
    ...(slugOverride ? { slugOverride } : {}),
  }));
}

export function cityNameToSlug(name: string, slugOverride?: string): string {
  if (slugOverride) return slugOverride + "-ca";
  return (
    name
      .toLowerCase()
      .normalize("NFD")
      .replace(/[̀-ͯ]/g, "")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "") + "-ca"
  );
}
